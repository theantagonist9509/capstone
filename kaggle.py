#!/usr/bin/env python3
"""
kaggle.py — convert a `# %%`-annotated run script into a Kaggle notebook
and optionally push it to the kernel.

Cell splitting is done by **jupytext** (the scripts' `# %%` markers are its
light format); this script only prepends a markdown header and a bootstrap
cell that prepares the Kaggle environment (clones the repo, copies the
datasets into the clone, fixes ``__file__`` / ``sys.argv``, enables inline
plots). The dataset is inferred from the script path (``runs/<dataset>/…``,
see ``DATASETS``), which also selects the dataset sources attached on push.
The resulting .ipynb can be uploaded manually in the Kaggle GUI or pushed with
``--push-run`` / ``--push-no-run`` — the full procedure lives in ``kaggle.md``.

Usage:
  python kaggle.py runs/shapes/train_classifier.py
  python kaggle.py runs/shapes/train_classifier.py --smoke
  python kaggle.py runs/shapes/traverse.py -o /tmp/traverse.ipynb
  python kaggle.py runs/kather-et-al-2018/train_classifier.py -o /tmp/kather.ipynb
  python kaggle.py runs/shapes/train_classifier.py --smoke --push-run
  python kaggle.py runs/shapes/train_classifier.py --smoke --push-no-run

The .py file stays the source of truth and remains runnable locally:
  python runs/shapes/train_classifier.py --smoke
  python runs/kather-et-al-2018/train_classifier.py --smoke
"""

import argparse
import hashlib
import json
import os
import sys

REPO_URL = "https://github.com/theantagonist9509/capstone.git"
DEFAULT_KERNEL_ID = "muplus2sigma/btp-26"

# Datasets the notebooks can use, keyed by the `runs/<name>/` directory they
# live under. Each entry is a list of Kaggle sources, all copied into the
# clone as `dataset/<dest>`:
#   kaggle_source : dataset to attach on push (None = attach manually)
#   required      : entries that must all exist in the dataset directory
#   dest          : name under `dataset/` that the run scripts read
#   hint          : substrings that must appear in the mounted path; needed
#                   when several sources share the same `required` entries
#                   (e.g. both Kather sets have the same class folders)
KATHER_CLASSES = ["ADI", "BACK", "DEB", "LYM", "MUC", "MUS", "NORM", "STR", "TUM"]

DATASETS = {
    "shapes": [
        {
            "kaggle_source": "smeschke/four-shapes",
            "required": ["circle", "square", "star", "triangle"],
            "dest": "shapes",
            "hint": None,
        },
    ],
    "kather-et-al-2018": [
        {
            "kaggle_source": "imrankhan77/nct-crc-he-100k",
            "required": KATHER_CLASSES,
            "dest": "NCT-CRC-HE-100K",
            "hint": ["nct-crc-he-100k", "NCT-CRC-HE-100K"],
        },
        {
            "kaggle_source": "imrankhan77/crc-val-he-7k",
            "required": KATHER_CLASSES,
            "dest": "CRC-VAL-HE-7K",
            "hint": ["crc-val-he-7k", "CRC-VAL-HE-7K"],
        },
    ],
}


def repo_root() -> str:
    return os.path.dirname(os.path.abspath(__file__))


def dataset_for_script(script_rel: str) -> str:
    """Infer the dataset from the script path: `runs/<dataset>/script.py`."""
    parts = script_rel.split("/")
    if len(parts) >= 2 and parts[0] == "runs" and parts[1] in DATASETS:
        return parts[1]
    raise SystemExit(
        f"cannot infer dataset from '{script_rel}': expected "
        f"runs/<dataset>/… with <dataset> in {sorted(DATASETS)}"
    )


def bootstrap_code(script_rel: str, extra_argv, dataset: str) -> str:
    """The Kaggle setup cell, parameterised by script path, extra CLI args and
    the dataset (inferred from the script path). Each dataset source is copied
    into the clone as `dataset/<dest>`."""
    argv_repr = repr([script_rel] + list(extra_argv))
    sources_repr = repr([
        {"dest": s["dest"], "required": sorted(s["required"]), "hint": s["hint"]}
        for s in DATASETS[dataset]
    ])
    return f'''\
# ── Kaggle bootstrap (generated by kaggle.py — edit the generator, not this cell)
import os, shutil, subprocess, sys, time
_t0 = time.time()
%matplotlib inline

import torch

# /kaggle/working persists between runs on a kernel, so a previous clone can
# be stale — always sync it to main (untracked files like checkpoints/ stay).
ROOT = "/kaggle/working/capstone"
if os.path.isdir(os.path.join(ROOT, ".git")):
    subprocess.run(["git", "-C", ROOT, "fetch", "--depth", "1", "origin", "main"], check=True)
    subprocess.run(["git", "-C", ROOT, "reset", "--hard", "FETCH_HEAD"], check=True)
else:
    if os.path.isdir(ROOT):
        shutil.rmtree(ROOT)
    subprocess.run(["git", "clone", "--depth", "1", "{REPO_URL}", ROOT], check=True)
print("[bootstrap] repo at commit:", subprocess.check_output(
    ["git", "-C", ROOT, "rev-parse", "--short", "HEAD"], text=True).strip())

# Dependencies (e.g. pytorch-msssim) come from the kernel's package-manager
# attachment — no pip installs here. See kaggle.md.

# Copy each attached dataset into the clone as dataset/<dest>. Reading through
# the /kaggle/input mount is slow (especially for the 100k small TIFFs), so the
# clone gets a real copy; /kaggle/working persists, so later runs skip it.
# CAPSTONE_USE_INPUT=1 skips the copy and lets the run scripts read the mount.
_sources = {sources_repr}
_COMPLETE = ".bootstrap_complete"
_USE_INPUT = os.environ.get("CAPSTONE_USE_INPUT", "0").lower() in ("1", "true", "yes")


def _looks_like(path, required):
    try:
        return set(required).issubset(set(os.listdir(path)))
    except OSError:
        return False


def _matches_hint(path, hint):
    if hint is None:
        return True
    path = path.lower()
    return any(h.lower() in path for h in hint)


def _find_source(spec):
    for _dirpath, _dirnames, _ in os.walk("/kaggle/input"):
        if _dirpath.count(os.sep) > 7:
            _dirnames[:] = []
            continue
        if (_looks_like(_dirpath, spec["required"])
                and _matches_hint(_dirpath, spec["hint"])):
            return _dirpath
    return None


def _copy_tree(src, dst, workers=(os.cpu_count() or 4) * 2):
    # The reads are I/O-bound, so a thread pool overlaps the per-file latency
    # instead of copying strictly one file at a time.
    from concurrent.futures import ThreadPoolExecutor, as_completed

    try:
        from tqdm.auto import tqdm as _tqdm
    except Exception:
        _tqdm = None

    pairs = []
    for _dirpath, _, _filenames in os.walk(src):
        _rel = os.path.relpath(_dirpath, src)
        _out = dst if _rel == "." else os.path.join(dst, _rel)
        os.makedirs(_out, exist_ok=True)
        for _f in _filenames:
            pairs.append((os.path.join(_dirpath, _f), os.path.join(_out, _f)))

    _label = os.path.basename(dst)
    if _label.endswith(".tmp"):
        _label = _label[:-4]

    with ThreadPoolExecutor(max_workers=workers) as _ex:
        _futs = [_ex.submit(shutil.copyfile, _s, _d) for _s, _d in pairs]
        _done = as_completed(_futs)
        if _tqdm is not None:
            _done = _tqdm(_done, total=len(_futs), unit="file", leave=False,
                          desc=f"[bootstrap] copy {{_label}}")
        for _fut in _done:
            _fut.result()
    return len(pairs)


for _src in _sources:
    _ds_src = _find_source(_src)
    if _ds_src is None:
        raise SystemExit(
            f"[bootstrap] dataset '{{_src['dest']}}' not found under /kaggle/input "
            f"(need {{sorted(_src['required'])}}"
            + (f", path hint {{_src['hint']}}" if _src["hint"] else "") + ")")

    if _USE_INPUT:
        print(f"[bootstrap] CAPSTONE_USE_INPUT=1 — using mount directly: {{_ds_src}}")
        continue

    _ds_dst = os.path.join(ROOT, "dataset", _src["dest"])
    if os.path.islink(_ds_dst) or os.path.isfile(_ds_dst):
        # stale symlink/file from an older bootstrap — replace with a real copy
        os.unlink(_ds_dst)
    if os.path.isdir(_ds_dst):
        _ready = os.path.join(_ds_dst, _COMPLETE)
        if _looks_like(_ds_dst, _src["required"]) and os.path.isfile(_ready):
            print(f"[bootstrap] dataset already copied — skipping: {{_ds_dst}}")
            continue
        # incomplete/legacy copy — rebuild it
        shutil.rmtree(_ds_dst)

    # Copy into a temp dir and rename atomically: an interrupted run must not
    # leave a half-populated dataset that the "already copied" check would trust.
    _tmp_dst = _ds_dst + ".tmp"
    if os.path.isdir(_tmp_dst):
        shutil.rmtree(_tmp_dst)
    elif os.path.exists(_tmp_dst):
        os.unlink(_tmp_dst)
    os.makedirs(os.path.dirname(_ds_dst), exist_ok=True)
    _t_copy = time.time()
    try:
        _n_files = _copy_tree(_ds_src, _tmp_dst)
        open(os.path.join(_tmp_dst, _COMPLETE), "w").close()
        os.replace(_tmp_dst, _ds_dst)
    except BaseException:
        shutil.rmtree(_tmp_dst, ignore_errors=True)
        raise
    print(f"[bootstrap] dataset copied: {{_ds_src}} -> {{_ds_dst}} "
          f"({{_n_files}} files, {{time.time() - _t_copy:.1f}}s)")

sys.path.insert(0, ROOT)
# Re-point __file__ so the script's repo-root math resolves inside the clone,
# and sanitise sys.argv for argparse (ipykernel leaves runtime flags behind).
__file__ = os.path.join(ROOT, "{script_rel}")
sys.argv = {argv_repr}
print("[bootstrap] GPU:", torch.cuda.get_device_name(0) if torch.cuda.is_available() else "none")
print(f"[bootstrap] done in {{time.time() - _t0:.1f}}s")
'''


def cell_id(kind: str, source: str) -> str:
    return hashlib.sha1(f"{kind}:{source}".encode()).hexdigest()[:8]


def _cell_source(cell) -> str:
    src = cell.get("source") or ""
    return "".join(src) if isinstance(src, list) else src


def build_notebook(script_path: str, extra_argv) -> dict:
    """Notebook = jupytext-parsed script cells, prefixed with a markdown
    header and the Kaggle bootstrap cell. The dataset is inferred from the
    script path (`runs/<dataset>/…`)."""
    import jupytext
    from nbformat.v4 import new_code_cell, new_markdown_cell

    script_rel = os.path.relpath(script_path, repo_root()).replace(os.sep, "/")
    dataset = dataset_for_script(script_rel)
    nb = jupytext.read(script_path)
    if not nb.cells:
        raise SystemExit(f"{script_path}: no cells found")

    md_title = (
        f"# `{script_rel}`\n\n"
        f"Generated by `kaggle.py` (jupytext) from the annotated script — edit "
        f"the .py, not this notebook. Dataset: `{dataset}`. "
        f"argv: `{sys.argv if extra_argv else '[]'}`\n"
    )
    header = new_markdown_cell(md_title)
    header["id"] = cell_id("markdown", md_title)
    boot = new_code_cell(bootstrap_code(script_rel, extra_argv, dataset))
    boot["id"] = cell_id("code", _cell_source(boot))

    cells = [header, boot]
    for cell in nb.cells:
        if "id" not in cell:
            cell["id"] = cell_id(cell["cell_type"], _cell_source(cell))
        cells.append(cell)
    nb.cells = cells

    md = dict(nb.get("metadata") or {})
    md.setdefault("kernelspec",
                  {"display_name": "Python 3", "language": "python", "name": "python3"})
    md.setdefault("language_info", {"name": "python"})
    nb["metadata"] = md
    return nb


def _import_kaggle_package():
    """Import the installed `kaggle` package (authenticates on import).

    This file is named `kaggle.py` at the repo root, so a bare
    `import kaggle` run from `python kaggle.py` would resolve to *this* file
    (sys.path[0] is the script's directory). Temporarily drop the repo root
    from sys.path so the real package in site-packages wins.
    """
    import importlib

    repo = repo_root()
    saved = sys.path[:]
    try:
        sys.path = [
            p for p in saved
            if os.path.abspath(p or os.getcwd()) != repo
        ]
        return importlib.import_module("kaggle")
    finally:
        sys.path = saved


def push_notebook(nb_path: str, kernel_id: str, run: bool, dataset: str) -> None:
    """Upload the .ipynb to a Kaggle kernel.

    run=True  → SAVE_AND_RUN_ALL (same as `kaggle kernels push`)
    run=False → QUICK_SAVE (update the kernel, do not start a session)
    """
    kaggle = _import_kaggle_package()
    from kagglesdk.kernels.types.kernels_api_service import (  # noqa: PLC0415
        ApiSaveKernelRequest,
        KernelExecutionType,
    )

    if "/" not in kernel_id:
        raise SystemExit(f"kernel id must be 'owner/slug', got: {kernel_id}")

    with open(nb_path, encoding="utf-8") as f:
        nb = json.load(f)
    for cell in nb.get("cells", []):
        if cell.get("cell_type") == "code":
            cell["outputs"] = []
            cell["execution_count"] = None
        src = cell.get("source")
        if isinstance(src, list):  # the API expects a single string
            cell["source"] = "".join(src)

    req = ApiSaveKernelRequest()
    req.slug = kernel_id
    req.new_title = kernel_id.split("/", 1)[1]  # must slugify to the slug
    req.text = json.dumps(nb)
    req.language = "python"
    req.kernel_type = "notebook"
    req.is_private = True
    req.enable_gpu = True
    req.enable_tpu = False
    req.enable_internet = True
    sources = [s["kaggle_source"] for s in DATASETS[dataset] if s["kaggle_source"]]
    missing = [s["dest"] for s in DATASETS[dataset] if not s["kaggle_source"]]
    if sources:
        req.dataset_data_sources = sources
    if missing:
        print(f"warning: no Kaggle source configured for {missing} in dataset "
              f"'{dataset}' — attach them to the kernel manually", file=sys.stderr)
    req.competition_data_sources = []
    req.kernel_data_sources = []
    req.model_data_sources = []
    req.kernel_execution_type = (
        KernelExecutionType.SAVE_AND_RUN_ALL if run else KernelExecutionType.QUICK_SAVE
    )

    with kaggle.api.build_kaggle_client() as client:
        resp = client.kernels.kernels_api_client.save_kernel(req)
    if getattr(resp, "error", None):
        raise SystemExit(f"push failed: {resp.error}")
    action = "pushed, run started" if run else "saved (not run)"
    print(f"{action}: https://www.kaggle.com/code/{kernel_id}")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("script", help="annotated .py (path inside the repo)")
    ap.add_argument("-o", "--output", help="output .ipynb (default: alongside the script)")
    ap.add_argument("--smoke", action="store_true", help="pass --smoke to the script")
    ap.add_argument("--extra-args", default="", help="other args to pass through, quoted")
    ap.add_argument("--kernel", default=DEFAULT_KERNEL_ID,
                    help=f"kernel to push to (default: {DEFAULT_KERNEL_ID})")
    group = ap.add_mutually_exclusive_group()
    group.add_argument("--push-run", action="store_true",
                       help="push the notebook to the kernel AND start a run")
    group.add_argument("--push-no-run", action="store_true",
                       help="push the notebook to the kernel without running it")
    args = ap.parse_args()

    root = repo_root()
    script_path = os.path.abspath(args.script)
    if not script_path.startswith(root):
        print(f"warning: {script_path} is outside the repo; relative paths may break",
              file=sys.stderr)

    extra_argv = []
    if args.smoke:
        extra_argv.append("--smoke")
    extra_argv += [a for a in args.extra_args.split() if a]

    script_rel = os.path.relpath(script_path, root).replace(os.sep, "/")
    dataset = dataset_for_script(script_rel)
    nb = build_notebook(script_path, extra_argv)

    out = args.output or os.path.splitext(script_path)[0] + ".ipynb"
    import jupytext  # noqa: PLC0415 — already imported by build_notebook
    jupytext.write(nb, out)

    n_code = sum(1 for c in nb["cells"] if c["cell_type"] == "code")
    n_md = len(nb["cells"]) - n_code
    print(f"wrote {out}  ({len(nb['cells'])} cells: {n_code} code, {n_md} markdown)")
    print(f"dataset: {dataset} | argv for script: {['<script>'] + extra_argv}")

    if args.push_run or args.push_no_run:
        push_notebook(out, args.kernel, run=args.push_run, dataset=dataset)


if __name__ == "__main__":
    main()
