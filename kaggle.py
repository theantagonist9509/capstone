#!/usr/bin/env python3
"""
kaggle.py — convert a `# %%`-annotated run script into a Kaggle notebook
and optionally push it to the kernel.

Cell splitting is done by **jupytext** (the scripts' `# %%` markers are its
light format); this script only prepends a markdown header and a bootstrap
cell that prepares the Kaggle environment (clones the repo, copies the
dataset into the clone, fixes ``__file__`` / ``sys.argv``, enables inline plots). The
resulting .ipynb can be uploaded manually in the Kaggle GUI or pushed with
``--push-run`` / ``--push-no-run`` — the full procedure lives in ``kaggle.md``.

Usage:
  python kaggle.py runs/shapes/train_classifier.py
  python kaggle.py runs/shapes/train_classifier.py --smoke
  python kaggle.py runs/shapes/traverse.py -o /tmp/traverse.ipynb
  python kaggle.py runs/shapes/train_classifier.py --smoke --push-run
  python kaggle.py runs/shapes/train_classifier.py --smoke --push-no-run

The .py file stays the source of truth and remains runnable locally:
  python runs/shapes/train_classifier.py --smoke
"""

import argparse
import hashlib
import json
import os
import sys

REPO_URL = "https://github.com/theantagonist9509/capstone.git"
DEFAULT_KERNEL_ID = "muplus2sigma/btp-26"
DEFAULT_DATASET_SOURCES = ["smeschke/four-shapes"]

# Subfolders of the attached Kaggle dataset that map onto ROOT/dataset/.
# Extend when new datasets are wired up (see kaggle.md).
DATASET_CLASS_DIRS = {
    "shapes": ["circle", "square", "star", "triangle"],
}


def repo_root() -> str:
    return os.path.dirname(os.path.abspath(__file__))


def bootstrap_code(script_rel: str, extra_argv) -> str:
    """The Kaggle setup cell, parameterised by script path + extra CLI args."""
    argv_repr = repr([script_rel] + list(extra_argv))
    class_sets = [f"{{{', '.join(repr(c) for c in dirs)}}}" for dirs in DATASET_CLASS_DIRS.values()]
    dataset_find = "\n".join(
        f"{'    if' if i == 0 else '        or'} {s}.issubset(set(_dirnames))"
        for i, s in enumerate(class_sets)
    )
    return f'''\
# ── Kaggle bootstrap (generated by kaggle.py — edit the generator, not this cell)
import os, shutil, subprocess, sys, time
_t0 = time.time()
%matplotlib inline

import torch

# /kaggle/working persists between runs on a kernel, so a previous clone can
# be stale — always sync it to main (untracked files like checkpoints/ stay).
ROOT = "/kaggle/working/capstone"
if os.path.isdir(os.path.join(ROOT, ".git")):
    subprocess.run(["git", "-C", ROOT, "fetch", "--depth", "1", "origin", "main"], check=True)
    subprocess.run(["git", "-C", ROOT, "reset", "--hard", "FETCH_HEAD"], check=True)
else:
    if os.path.isdir(ROOT):
        shutil.rmtree(ROOT)
    subprocess.run(["git", "clone", "--depth", "1", "{REPO_URL}", ROOT], check=True)
print("[bootstrap] repo at commit:", subprocess.check_output(
    ["git", "-C", ROOT, "rev-parse", "--short", "HEAD"], text=True).strip())

# Dependencies (e.g. pytorch-msssim) come from the kernel's package-manager
# attachment — no pip installs here. See kaggle.md.

# Locate the attached dataset by its class folders (mount layout varies).
_ds_src = None
for _dirpath, _dirnames, _ in os.walk("/kaggle/input"):
    if _dirpath.count(os.sep) > 7:
        _dirnames[:] = []
        continue
{dataset_find}:
        _ds_src = _dirpath
        break
if _ds_src is None:
    raise SystemExit("[bootstrap] dataset class folders not found under /kaggle/input")
_ds_dst = os.path.join(ROOT, "dataset", "{next(iter(DATASET_CLASS_DIRS))}")
os.makedirs(os.path.dirname(_ds_dst), exist_ok=True)
if os.path.islink(_ds_dst):
    # stale symlink from the old mount-through setup — replace with a real copy
    os.unlink(_ds_dst)
if os.path.exists(_ds_dst):
    print(f"[bootstrap] dataset already present — skipping copy: {{_ds_dst}}")
else:
    # Reading through the /kaggle/input mount is slow — copy once into the
    # working clone (/kaggle/working persists between kernel runs).
    shutil.copytree(_ds_src, _ds_dst)
    print(f"[bootstrap] dataset copied: {{_ds_src}} -> {{_ds_dst}}")

sys.path.insert(0, ROOT)
# Re-point __file__ so the script's repo-root math resolves inside the clone,
# and sanitise sys.argv for argparse (ipykernel leaves runtime flags behind).
__file__ = os.path.join(ROOT, "{script_rel}")
sys.argv = {argv_repr}
print("[bootstrap] GPU:", torch.cuda.get_device_name(0) if torch.cuda.is_available() else "none")
print(f"[bootstrap] done in {{time.time() - _t0:.1f}}s")
'''


def cell_id(kind: str, source: str) -> str:
    return hashlib.sha1(f"{kind}:{source}".encode()).hexdigest()[:8]


def _cell_source(cell) -> str:
    src = cell.get("source") or ""
    return "".join(src) if isinstance(src, list) else src


def build_notebook(script_path: str, extra_argv) -> dict:
    """Notebook = jupytext-parsed script cells, prefixed with a markdown
    header and the Kaggle bootstrap cell."""
    import jupytext
    from nbformat.v4 import new_code_cell, new_markdown_cell

    script_rel = os.path.relpath(script_path, repo_root()).replace(os.sep, "/")
    nb = jupytext.read(script_path)
    if not nb.cells:
        raise SystemExit(f"{script_path}: no cells found")

    md_title = (
        f"# `{script_rel}`\n\n"
        f"Generated by `kaggle.py` (jupytext) from the annotated script — edit "
        f"the .py, not this notebook. argv: `{sys.argv if extra_argv else '[]'}`\n"
    )
    header = new_markdown_cell(md_title)
    header["id"] = cell_id("markdown", md_title)
    boot = new_code_cell(bootstrap_code(script_rel, extra_argv))
    boot["id"] = cell_id("code", _cell_source(boot))

    cells = [header, boot]
    for cell in nb.cells:
        if "id" not in cell:
            cell["id"] = cell_id(cell["cell_type"], _cell_source(cell))
        cells.append(cell)
    nb.cells = cells

    md = dict(nb.get("metadata") or {})
    md.setdefault("kernelspec",
                  {"display_name": "Python 3", "language": "python", "name": "python3"})
    md.setdefault("language_info", {"name": "python"})
    nb["metadata"] = md
    return nb


def _import_kaggle_package():
    """Import the installed `kaggle` package (authenticates on import).

    This file is named `kaggle.py` at the repo root, so a bare
    `import kaggle` run from `python kaggle.py` would resolve to *this* file
    (sys.path[0] is the script's directory). Temporarily drop the repo root
    from sys.path so the real package in site-packages wins.
    """
    import importlib

    repo = repo_root()
    saved = sys.path[:]
    try:
        sys.path = [
            p for p in saved
            if os.path.abspath(p or os.getcwd()) != repo
        ]
        return importlib.import_module("kaggle")
    finally:
        sys.path = saved


def push_notebook(nb_path: str, kernel_id: str, run: bool) -> None:
    """Upload the .ipynb to a Kaggle kernel.

    run=True  → SAVE_AND_RUN_ALL (same as `kaggle kernels push`)
    run=False → QUICK_SAVE (update the kernel, do not start a session)
    """
    kaggle = _import_kaggle_package()
    from kagglesdk.kernels.types.kernels_api_service import (  # noqa: PLC0415
        ApiSaveKernelRequest,
        KernelExecutionType,
    )

    if "/" not in kernel_id:
        raise SystemExit(f"kernel id must be 'owner/slug', got: {kernel_id}")

    with open(nb_path, encoding="utf-8") as f:
        nb = json.load(f)
    for cell in nb.get("cells", []):
        if cell.get("cell_type") == "code":
            cell["outputs"] = []
            cell["execution_count"] = None
        src = cell.get("source")
        if isinstance(src, list):  # the API expects a single string
            cell["source"] = "".join(src)

    req = ApiSaveKernelRequest()
    req.slug = kernel_id
    req.new_title = kernel_id.split("/", 1)[1]  # must slugify to the slug
    req.text = json.dumps(nb)
    req.language = "python"
    req.kernel_type = "notebook"
    req.is_private = True
    req.enable_gpu = True
    req.enable_tpu = False
    req.enable_internet = True
    req.dataset_data_sources = list(DEFAULT_DATASET_SOURCES)
    req.competition_data_sources = []
    req.kernel_data_sources = []
    req.model_data_sources = []
    req.kernel_execution_type = (
        KernelExecutionType.SAVE_AND_RUN_ALL if run else KernelExecutionType.QUICK_SAVE
    )

    with kaggle.api.build_kaggle_client() as client:
        resp = client.kernels.kernels_api_client.save_kernel(req)
    if getattr(resp, "error", None):
        raise SystemExit(f"push failed: {resp.error}")
    action = "pushed, run started" if run else "saved (not run)"
    print(f"{action}: https://www.kaggle.com/code/{kernel_id}")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("script", help="annotated .py (path inside the repo)")
    ap.add_argument("-o", "--output", help="output .ipynb (default: alongside the script)")
    ap.add_argument("--smoke", action="store_true", help="pass --smoke to the script")
    ap.add_argument("--extra-args", default="", help="other args to pass through, quoted")
    ap.add_argument("--kernel", default=DEFAULT_KERNEL_ID,
                    help=f"kernel to push to (default: {DEFAULT_KERNEL_ID})")
    group = ap.add_mutually_exclusive_group()
    group.add_argument("--push-run", action="store_true",
                       help="push the notebook to the kernel AND start a run")
    group.add_argument("--push-no-run", action="store_true",
                       help="push the notebook to the kernel without running it")
    args = ap.parse_args()

    root = repo_root()
    script_path = os.path.abspath(args.script)
    if not script_path.startswith(root):
        print(f"warning: {script_path} is outside the repo; relative paths may break",
              file=sys.stderr)

    extra_argv = []
    if args.smoke:
        extra_argv.append("--smoke")
    extra_argv += [a for a in args.extra_args.split() if a]

    nb = build_notebook(script_path, extra_argv)

    out = args.output or os.path.splitext(script_path)[0] + ".ipynb"
    import jupytext  # noqa: PLC0415 — already imported by build_notebook
    jupytext.write(nb, out)

    n_code = sum(1 for c in nb["cells"] if c["cell_type"] == "code")
    n_md = len(nb["cells"]) - n_code
    print(f"wrote {out}  ({len(nb['cells'])} cells: {n_code} code, {n_md} markdown)")
    print(f"argv for script: {['<script>'] + extra_argv}")

    if args.push_run or args.push_no_run:
        push_notebook(out, args.kernel, run=args.push_run)


if __name__ == "__main__":
    main()
