#!/usr/bin/env python3
"""
py2nb — convert a `# %%`-annotated run script into a Kaggle notebook.

Splits the script on jupytext-style cell markers and prepends a bootstrap
cell that prepares the Kaggle environment (clones the repo, installs deps,
symlinks the dataset, fixes ``__file__`` / ``sys.argv``, enables inline
plots). The resulting .ipynb is pushed with ``kaggle kernels push`` — the
full procedure lives in ``kaggle.md``.

Usage:
  python tools/py2nb.py runs/shapes/train_classifier.py
  python tools/py2nb.py runs/shapes/train_classifier.py --smoke
  python tools/py2nb.py runs/shapes/traverse.py -o /tmp/traverse.ipynb

The .py file stays the source of truth and remains runnable locally:
  python runs/shapes/train_classifier.py --smoke
"""

import argparse
import hashlib
import json
import os
import re
import sys

REPO_URL = "https://github.com/theantagonist9509/capstone.git"

# Subfolders of the attached Kaggle dataset that map onto ROOT/dataset/.
# Extend when new datasets are wired up (see kaggle.md).
DATASET_CLASS_DIRS = {
    "shapes": ["circle", "square", "star", "triangle"],
}

CELL_MARKER = re.compile(r"^# %%(?P<md> \[markdown\])?\s*$")


def repo_root() -> str:
    return os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def split_cells(source: str):
    """Split an annotated .py into [(kind, lines), ...], kind in {'code','markdown'}."""
    cells = []
    cur_kind, cur_lines = None, []
    for line in source.splitlines():
        m = CELL_MARKER.match(line)
        if m:
            if cur_kind is not None:
                cells.append((cur_kind, cur_lines))
            cur_kind = "markdown" if m.group("md") else "code"
            cur_lines = []
        else:
            if cur_kind is None:  # preamble before the first marker → code
                cur_kind, cur_lines = "code", []
            cur_lines.append(line)
    if cur_kind is not None:
        cells.append((cur_kind, cur_lines))
    return cells


def clean_cell(kind: str, lines):
    """Drop leading/trailing blank lines; de-comment markdown cells."""
    body = list(lines)
    while body and not body[0].strip():
        body.pop(0)
    while body and not body[-1].strip():
        body.pop()
    if kind == "markdown":
        out = []
        for ln in body:
            out.append(re.sub(r"^# ?", "", ln))
        body = out
    return "\n".join(body) + "\n" if body else ""


def bootstrap_code(script_rel: str, extra_argv) -> str:
    """The Kaggle setup cell, parameterised by script path + extra CLI args."""
    argv_repr = repr([script_rel] + list(extra_argv))
    class_sets = [f"{{{', '.join(repr(c) for c in dirs)}}}" for dirs in DATASET_CLASS_DIRS.values()]
    dataset_find = "\n".join(
        f"{'    if' if i == 0 else '        or'} {s}.issubset(set(_dirnames))"
        for i, s in enumerate(class_sets)
    )
    return f'''\
# ── Kaggle bootstrap (generated by tools/py2nb.py — edit the generator, not this cell)
import os, subprocess, sys, time
sys.stdout.reconfigure(line_buffering=True)
sys.stderr.reconfigure(line_buffering=True)
_t0 = time.time()
%matplotlib inline

import torch

ROOT = "/kaggle/working/capstone"
if not os.path.isdir(os.path.join(ROOT, ".git")):
    subprocess.run(["git", "clone", "--depth", "1", "{REPO_URL}", ROOT], check=True)
print("[bootstrap] cloned commit:", subprocess.check_output(
    ["git", "-C", ROOT, "rev-parse", "--short", "HEAD"], text=True).strip())

# Dependencies (e.g. pytorch-msssim) come from the kernel's package-manager
# attachment — no pip installs here. See kaggle.md.

# Locate the attached dataset by its class folders (mount layout varies).
_ds_src = None
for _dirpath, _dirnames, _ in os.walk("/kaggle/input"):
    if _dirpath.count(os.sep) > 7:
        _dirnames[:] = []
        continue
{dataset_find}:
        _ds_src = _dirpath
        break
if _ds_src is None:
    raise SystemExit("[bootstrap] dataset class folders not found under /kaggle/input")
_ds_dst = os.path.join(ROOT, "dataset", "{next(iter(DATASET_CLASS_DIRS))}")
os.makedirs(os.path.dirname(_ds_dst), exist_ok=True)
if not os.path.exists(_ds_dst):
    os.symlink(_ds_src, _ds_dst)
print(f"[bootstrap] dataset: {{_ds_src}} -> {{_ds_dst}}")

sys.path.insert(0, ROOT)
# Re-point __file__ so the script's repo-root math resolves inside the clone,
# and sanitise sys.argv for argparse (ipykernel leaves runtime flags behind).
__file__ = os.path.join(ROOT, "{script_rel}")
sys.argv = {argv_repr}
print("[bootstrap] GPU:", torch.cuda.get_device_name(0) if torch.cuda.is_available() else "none")
print(f"[bootstrap] done in {{time.time() - _t0:.1f}}s")
'''


def cell_id(kind: str, source: str) -> str:
    return hashlib.sha1(f"{kind}:{source}".encode()).hexdigest()[:8]


def build_notebook(script_path: str, extra_argv) -> dict:
    root = repo_root()
    script_rel = os.path.relpath(script_path, root).replace(os.sep, "/")
    with open(script_path, encoding="utf-8") as f:
        source = f.read()

    raw_cells = split_cells(source)
    if not raw_cells:
        raise SystemExit(f"{script_path}: no '# %%' cell markers found")

    cells = []
    md_title = (
        f"# `{script_rel}`\n\n"
        f"Generated by `tools/py2nb.py` from the annotated script — edit the "
        f".py, not this notebook. argv: `{sys.argv if extra_argv else '[]'}`\n"
    )
    cells.append({
        "cell_type": "markdown",
        "id": cell_id("markdown", md_title),
        "metadata": {},
        "source": md_title,
    })
    boot = bootstrap_code(script_rel, extra_argv)
    cells.append({
        "cell_type": "code",
        "execution_count": None,
        "id": cell_id("code", boot),
        "metadata": {},
        "outputs": [],
        "source": boot,
    })
    for kind, lines in raw_cells:
        body = clean_cell(kind, lines)
        if not body.strip():
            continue
        cells.append({
            "cell_type": kind,
            "id": cell_id(kind, body),
            "metadata": {},
            **({"outputs": [], "execution_count": None} if kind == "code" else {}),
            "source": body,
        })

    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("script", help="annotated .py (path inside the repo)")
    ap.add_argument("-o", "--output", help="output .ipynb (default: alongside the script)")
    ap.add_argument("--smoke", action="store_true", help="pass --smoke to the script")
    ap.add_argument("--extra-args", default="", help="other args to pass through, quoted")
    args = ap.parse_args()

    root = repo_root()
    script_path = os.path.abspath(args.script)
    if not script_path.startswith(root):
        print(f"warning: {script_path} is outside the repo; relative paths may break",
              file=sys.stderr)

    extra_argv = []
    if args.smoke:
        extra_argv.append("--smoke")
    extra_argv += [a for a in args.extra_args.split() if a]

    nb = build_notebook(script_path, extra_argv)

    out = args.output or os.path.splitext(script_path)[0] + ".ipynb"
    with open(out, "w", encoding="utf-8") as f:
        json.dump(nb, f, indent=1)
        f.write("\n")

    n_code = sum(1 for c in nb["cells"] if c["cell_type"] == "code")
    n_md = len(nb["cells"]) - n_code
    print(f"wrote {out}  ({len(nb['cells'])} cells: {n_code} code, {n_md} markdown)")
    print(f"argv for script: {['<script>'] + extra_argv}")


if __name__ == "__main__":
    main()
